from __future__ import annotations
import pandas as pd

WINDOW = 100      # 신고가 기준일
HOLD = 40         # 보유일
MKT_MA = 200      # 시장 추세 판정


def basket(daily: dict) -> pd.Series:
    """42코인 동일가중 지수. 상장 전 구간은 자동으로 빠진다."""
    px = {}
    for s, d in daily.items():
        x = d.copy()
        x["dt"] = pd.to_datetime(x["dt"])
        px[s] = x.set_index("dt")["close"]
    P = pd.DataFrame(px).sort_index()
    return (1 + P.pct_change().clip(-.5, .5).mean(axis=1).fillna(0)).cumprod()


def bull_days(daily: dict, ma=MKT_MA) -> pd.Series:
    """시장이 200일선 위인 날 = True."""
    b = basket(daily)
    return b > b.rolling(ma).mean()


def signals(d: pd.DataFrame, window=WINDOW):
    """마감가가 직전 window일 최고가 이상인 봉의 인덱스."""
    c = d["close"].values
    return [i for i in range(window, len(c)) if c[i] >= c[i - window:i].max()]
